def figures():
    meths = list(KEY)
    fig, axes = plt.subplots(2, 2, figsize=(COL_IN, 3.3), sharey=True)
    for i, (kind, klab) in enumerate((("clean", "Clean"), ("under faults", "Under faults"))):
        for j, (mod, mlab) in enumerate((("a", "No calibration"), ("b", "Calibrated (10/gas)"))):
            ax = axes[i, j]
            vals = [v(f"v2c {KEY[m]} model ({mod}) {kind}, pooled, value") for m in meths]
            has_ci = f"v2c {KEY[meths[0]]} model ({mod}) {kind}, pooled, ci_low" in PNV
            err = None
            if has_ci:
                lo = [v(f"v2c {KEY[m]} model ({mod}) {kind}, pooled, ci_low") for m in meths]
                hi = [v(f"v2c {KEY[m]} model ({mod}) {kind}, pooled, ci_high") for m in meths]
                err = [np.array(vals) - lo, np.array(hi) - vals]
            ax.bar(range(3), vals, color=[COLORS[m] for m in meths], yerr=err, capsize=2, width=0.7)
            ax.set_xticks(range(3), meths)
            ax.set_ylim(0, 1)
            if i == 0:
                ax.set_title(mlab)
            if j == 0:
                ax.set_ylabel(f"{klab}\nMacro-F1")
    fig.tight_layout(pad=0.4)
    fig.savefig(P / "fig4_recalibration.png", dpi=300)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(COL_IN, 2.2))
    w = 0.26
    for j, m in enumerate(meths):
        val = [v(f"v2c (b)-(a) {KEY[m]} clean, {s}, value") for s, _ in SUBSETS]
        lo = [v(f"v2c (b)-(a) {KEY[m]} clean, {s}, ci_low") for s, _ in SUBSETS]
        hi = [v(f"v2c (b)-(a) {KEY[m]} clean, {s}, ci_high") for s, _ in SUBSETS]
        ax.bar(np.arange(4) + (j - 1) * w, val, w, color=COLORS[m], label=m, yerr=[np.array(val) - lo, np.array(hi) - val], capsize=2)
    ax.axhline(0, color="black", lw=0.6)
    ax.set_xticks(range(4), [lab for _, lab in SUBSETS])
    ax.set_ylabel("Clean Macro-F1 gain")
    ax.set_ylim(min(0, min(v(f"v2c (b)-(a) {k} clean, {s}, ci_low") for k in KEY.values() for s, _ in SUBSETS)) - 0.01, 0.3)
    ax.legend(frameon=False, ncol=3, loc="upper left")
    fig.tight_layout(pad=0.4)
    fig.savefig(P / "fig5_gain_per_batch.png", dpi=300)
    plt.close(fig)


