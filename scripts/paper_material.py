def load_pn():
    d = {}
    for line in (P / "PAPER_NUMBERS.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("| ") and not line.startswith(("| number", "| quantity")):
            p = [x.strip() for x in line.strip().strip("|").split("|")]
            d[p[0]] = p[1]
    return d


PNV = load_pn()


def v(name):
    return float(PNV[name])


# ---- cells: text + the PAPER_NUMBERS names of its numbers, in order ---------------------------------------------------------------
def num(name, f="{:.3f}"):
    return f.format(v(name)), [name]


def ci(value, lo, hi, sign=True):
    """'+0.136 [0.117, 0.156]' with its three names."""
    return f"{v(value):+.3f} [{v(lo):.3f}, {v(hi):.3f}]" if sign else f"{v(value):.3f} [{v(lo):.3f}, {v(hi):.3f}]", [value, lo, hi]


def lit(text):
    return text, []


def join(*cells, sep=" + "):
    return sep.join(c[0] for c in cells), [n for c in cells for n in c[1]]


def table(fname, caption, label, colspec, header, rows, source, star=False):
    env = "table*" if star else "table"
    L = [f"% Source: {source}", "% Every number is a named row of results/paper/PAPER_NUMBERS.md (cell map: " + fname.replace(".tex", ".cells.json") + ");",
         "% generated by scripts/paper_material.py", f"\\begin{{{env}}}[t]", "\\centering", "\\footnotesize", f"\\caption{{{caption}}}",
         f"\\label{{{label}}}", "\\setlength{\\tabcolsep}{3pt}", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    cells = []
    for r, row in enumerate(rows):
        L.append(" & ".join(c[0] for c in row) + " \\\\")
        cells += [{"row": r, "col": c, "names": row[c][1]} for c in range(1, len(row)) if row[c][1]]
    L += ["\\bottomrule", "\\end{tabular}", f"\\end{{{env}}}"]
    (T / fname).write_text("\n".join(L) + "\n", encoding="utf-8")
    (T / fname.replace(".tex", ".cells.json")).write_text(json.dumps({"cells": cells}, indent=1), encoding="utf-8")


