"""Assemble results/preprocessing/REPORT.md (preprocessing study) from the result files.

Usage: python scripts/pp_report.py --config configs/preprocessing.yaml
Every number in the report is read from a CSV/JSON whose path is printed next to it. Nothing is typed by hand
except the rationale text and the list of what was not done.
"""
import argparse
import json
import xml.etree.ElementTree as ET
from pathlib import Path

import pandas as pd

from src.evaluate import load_decisions, load_split
from src.preprocessing import build_preprocessor, fit_preprocessor, pipeline_provenance
from src.data import xy
from src.splits import load_config

R = Path("results")
PP = R / "preprocessing"


def read(path, **kw):
    path = Path(path)
    return pd.read_csv(path, **kw) if path.exists() else None


def table(df, floatfmt=".4f"):
    return "(file missing)" if df is None else df.to_markdown(index=False, floatfmt=floatfmt)


def junit_status():
    path = PP / "junit.xml"
    if not path.exists():
        return None
    root = ET.parse(path).getroot()
    suite = root if root.tag == "testsuite" else root.find("testsuite")
    cases = {}
    for tc in suite.iter("testcase"):
        cases[f"{tc.get('classname')}::{tc.get('name')}"] = tc.find("failure") is None and tc.find("error") is None
    return cases


def gate(passed, evidence):
    return {"result": "PASS" if passed else "FAIL", "evidence": evidence}


def main(cfg_path):
    cfg = load_config(cfg_path)
    dec = load_decisions()
    out = []
    w = out.append

    cases = junit_status()
    n_tests, n_fail = (len(cases), sum(not v for v in cases.values())) if cases else (None, None)
    integ = json.load(open(PP / "phase1/temporal/integrity.json"))
    dropped = len(integ["cleaning_dropped_train"])
    inspected = integ["records"] + dropped

    def tests_like(*frags):
        sel = {k: v for k, v in (cases or {}).items() if any(f in k for f in frags)}
        return (len(sel) > 0 and all(sel.values())), len(sel)

    p2_ok, p2_n = tests_like("parameters_depend_on_train_batches_only", "never_reads", "never_read", "unrequested_batches")
    p4_ok, p4_n = tests_like("fault_changes_only_features_traced", "provenance_covers", "sensor_local_groups", "all_sensor_groups")
    nb = dec["new_baseline"]
    ref = nb["svm_tuned"]["macro_f1"]
    fin = dec["final_pipeline"]
    final_f1 = fin["baseline_svm_macro_f1"]
    repro = PP / "reproducibility.json"
    rj = json.load(open(repro)) if repro.exists() else None
    gates = {
        "P1 integrity": gate(inspected == 9546 and integ["nan"] == 0 and integ["inf"] == 0 and cases is not None and n_fail == 0,
                             f"{inspected} records inspected in batches 1-7 ({integ['records']} kept after dropping {dropped} corrupt "
                             f"Train records), NaN {integ['nan']}, inf {integ['inf']}, {n_tests} tests, {n_fail} failing "
                             f"[phase1/temporal/integrity.json, junit.xml]"),
        "P2 no leakage": gate(p2_ok, f"{p2_n} tests: fitted pipeline unchanged when batch 7 changes, changes when a Train batch changes, "
                                      f"Test files unparseable and never read [tests/test_preprocessing.py, test_protocols.py, test_data.py]"),
        "P3 no harm to clean performance": gate(final_f1 >= ref - cfg["final"]["p3_margin"] - 1e-12,
                                                f"final pipeline = new Baseline (no candidate adopted): SVM Macro-F1 {ref:.4f} (tuned), "
                                                f"gate >= {ref - cfg['final']['p3_margin']:.4f}; the old reference 0.868 is superseded "
                                                f"[phase3/new_baseline.json, phase45/decision_rule.csv]"),
        "P4 traceability": gate(p4_ok, f"{p4_n} tests + final/feature_provenance.csv; groups with a multi-sensor column are rejected "
                                       f"[phase4/candidates_val.csv]"),
        "P5 reconstruction": gate((PP / "phase1/protocol_comparison_summary.csv").exists(),
                                  "tables per method and per sensor, with and without the twin, both protocols "
                                  "[phase1/protocol_comparison_sensor.csv, protocol_comparison_summary.csv]"),
        "P6 reproducibility": gate(bool(rj and rj["reproducible"]),
                                   "not verified yet" if rj is None else
                                   f"{rj['files_compared']} files compared with the previous run, {rj['files_differing']} differing "
                                   f"[reproducibility.json]"),
    }
    if rj is None:
        gates["P6 reproducibility"]["result"] = "NOT RUN"

    w("# Preprocessing report\n")
    w("Generated by `scripts/pp_report.py`. Every number comes from the file named next to it (paths relative to `results/preprocessing/` "
      "unless stated). Validation = batch 7, Train = batches 1-6, Test (8-10) was never read.\n")

    w("## 1. What was done\n")
    d = read(R / "main_cleaned/diagnosis/design_2x2.csv")
    w(f"* **Data integrity and cleaning.** {inspected} records in batches 1-7; the invalid-value rule (|x-median|/MAD > 1000, fitted on Train) "
      f"removes {dropped} corrupt Train records and only counts evaluation ones (`cleaning/invalid_records_temporal.csv`). They had inflated the Train "
      f"standard deviation of S06 |DR| by x316 (`../main_cleaned/diagnosis/std_s05_s08_before_after.csv`); the old SVM Macro-F1 of 0.878 was "
      f"inflated by 0.022 (`../main_cleaned/diagnosis/design_2x2.csv`).")
    w("* **Phase 1, reconstruction of a sensor block**: Ridge in slog space is best; see section 3 "
      "(`phase1/protocol_comparison_summary.csv`). The mean and median fill-ins are worse than predicting the evaluation mean for all 16 sensors.")
    o2 = read(PP / "phase2/outlier_options_val.csv", index_col=0)
    w(f"* **Phase 2, outliers (IQR)**: kept (winsorising SVM Macro-F1 {o2.loc['winsorize', 'svm_macro_f1']:.4f} vs {o2.loc['keep_all', 'svm_macro_f1']:.4f}); "
      f"clipping does not hide a Bias fault (`phase2/bias_hiding_summary.csv`). Outliers are drift, not noise (`phase2/outlier_summary.json`).")
    sc = read(PP / "phase3/scaling_options_val.csv", index_col=0)
    st = json.load(open(PP / "phase3/stress_check.json"))
    w(f"* **Phase 3, scaling**: MinMax looked best ({sc.loc['minmax', 'svm_macro_f1']:.4f}) but the stress check showed the gain comes from squeezing "
      f"{len(st['features_squeezed_below_flag'])} features with extreme values (percentile-bounded MinMax gain {st['condition_B_percentile_minmax_gain_over_standard']:+.4f}); "
      f"StandardScaler is kept (`phase3/stress_*.csv`, `phase3/stress_check.json`). LightGBM varies by {sc['lgbm_macro_f1'].max() - sc['lgbm_macro_f1'].min():.3f} "
      f"across scalers, so it is not exactly scale-invariant in practice.")
    p4 = read(PP / "phase4/candidates_val.csv")
    w(f"* **Phase 4, engineered features**: two sensor-local groups were tried; both lower SVM Macro-F1 "
      f"(`phase4/candidates_val.csv`). The array-normalisation groups were rejected by P4 because they depend on all 16 sensors.")
    p5 = read(PP / "phase5/drift_options_val.csv", index_col=0)
    w(f"* **Phase 5, drift filter**: excluding the most drift-sensitive 10%/20% lowers SVM Macro-F1 ({p5.loc['drop_top10', 'svm_macro_f1']:.4f}/"
      f"{p5.loc['drop_top20', 'svm_macro_f1']:.4f} vs {p5.loc['none', 'svm_macro_f1']:.4f}) (`phase5/drift_options_val.csv`).")
    rule = read(PP / "phase45/decision_rule.csv")
    w(f"* **Decision rule** (gain > 0.005 and bootstrap interval excludes 0): {int(rule['adopt'].sum())} of {len(rule)} candidates adopted "
      f"(`phase45/decision_rule.csv`). **The final preprocessing is the Baseline: StandardScaler on the 128 raw features, after the data cleaning rule.**")
    a = read(PP / "final/aug_baselines_summary.csv")
    w("\nNew baselines on the final pipeline, Validation, augmentation with 5 seeds (`final/aug_baselines_summary.csv`):\n")
    w(table(a) + "\n")

    w("## 2. Gates\n")
    w("| gate | result | evidence |\n|---|---|---|")
    for k, g in gates.items():
        w(f"| {k} | {g['result']} | {g['evidence']} |")
    w("")

    w("## 3. Combinations compared on Validation (at most 12)\n")
    tr = read(PP / "trials.csv")
    wanted = ["P3-standard", "P3-minmax", "P3b-minmax_p1_99", "P3-robust", "P3-robust+slog", "P3-standard+slog", "P2-winsorize",
              "P2-drop_train_rows", "P4-trans_ratio", "P4-ema_shape", "P5-drop_top10", "P5-drop_top20"]
    rows = tr[tr["trial_id"].isin(wanted)].drop_duplicates("trial_id").set_index("trial_id").loc[wanted].reset_index()
    assert len(rows) <= cfg["final"]["max_candidates"]
    comp = rows[["trial_id", "svm_macro_f1", "svm_accuracy", "lgbm_macro_f1", "lgbm_accuracy"]].copy()
    base = comp.loc[comp.trial_id == "P3-standard", "svm_macro_f1"].iloc[0]
    comp["svm_vs_baseline"] = comp["svm_macro_f1"] - base
    w("Fixed model settings (C=10, gamma=scale; LightGBM 15 leaves) so only the preprocessing changes (`trials.csv`). "
      f"All {len(tr)} trials of the study are logged in `trials.csv`.\n")
    w(table(comp) + "\n")
    w("Ablation reading: every row is one change relative to the Baseline row `P3-standard`; the last column is its effect on SVM Macro-F1.\n")

    w("## 4. Final pipeline and rationale\n")
    w("`raw 128 features -> StandardScaler (fitted on cleaned Train) -> NaN->0 for the SVM` (LightGBM takes NaN natively), preceded by the data "
      "cleaning rule on the Train rows.\n")
    w("* **Cleaning rule**: corrupt records change the scaler statistics by orders of magnitude (see `DATA_CLEANING_RULE.md`).")
    w("* **StandardScaler**: the MinMax advantage disappears when the squeezing of 11 features is removed (`phase3/stress_check.json`).")
    w("* **No clipping, no engineered features, no drift filter**: none passed the pre-registered rule (`phase45/decision_rule.csv`).")
    w("* **Provenance**: all 128 columns are single-sensor blocks (`final/feature_provenance.csv`).")
    w("\nReferences actually consulted: Fonollosa, Rodriguez-Lujan, Huerta, *Chemical gas sensor array dataset*, Data in Brief 2015 (PMC4510048; sensor types, EMA definition). "
      "Vergara et al., Sens. Actuators B 166-167:320-329, 2012 (dataset). Yan et al., *Electronic nose feature extraction methods: a review*, Sensors 15(11):27804, 2015 "
      "(normalisation taxonomy; array normalisation and the fractional-difference linearisation claim). Muezzinoglu et al., Sens. Actuators B 137(2):507-512, 2009 "
      "(existence, title and venue checked; the text was not read). Troyanskaya et al., Bioinformatics 17(6):520-525, 2001 (kNN imputation) and van Buuren and "
      "Groothuis-Oudshoorn, J. Stat. Softw. 45:1-67, 2011 (iterative imputation), both as cited by the scikit-learn documentation. Tukey, *Exploratory Data Analysis*, "
      "Addison-Wesley 1977 (inner fences). Cohen, *Statistical Power Analysis for the Behavioral Sciences*, 1988 (Cramer's V >= 0.1 as a small effect): "
      "cited from memory, not checked online. The exact feature ratios of Phase 4 are our construction; no reference proposes them. "
      "The official UCI feature definition of |DR| is ambiguous and the formulas of DR/|DR| were not found in any source reached; no feature relies on them.\n")

    w("## 5. Not done, and why\n")
    for line in [
        "Mode imputation: not applicable, all 128 features are continuous.",
        "Mutual information / ANOVA-F ranking and the |r| > 0.95 redundancy filter: dropped to save time (agreed shortened Phase 5).",
        "Cross-sensor-type ratios: the index-to-type mapping (TGS2600/2602/2610/2620) is not documented, only four of each type are known.",
        "Twin difference as a classification feature: it would let the classifier see a replica disagreement, i.e. the fault itself, and blur the separation between detection and classification; it is left to the reliability module.",
        "Array normalisation (pn_l2, pn_logmed): best single group for LightGBM (pn_l2: see `phase4/candidates_val.csv`) but a fault in one sensor changes the features of all 16 sensors, so P4 rejects it.",
        "Deleting statistical outliers from Validation: never done; Train rows are dropped only by the invalid-value rule.",
    ]:
        w(f"* {line}")

    w("\n## 6. Impact on the next steps\n")
    old = read(R / "main/02_baselines/clean_val.csv")
    new = read(R / "main_cleaned/02_baselines/clean_val.csv")
    if old is not None and new is not None:
        cmp_ = old.merge(new, on="model", suffixes=("_old_uncleaned", "_cleaned"))
        w("Baseline Macro-F1 before and after cleaning (`../main/02_baselines/clean_val.csv`, `../main_cleaned/02_baselines/clean_val.csv`):\n")
        w(table(cmp_[["model", "macro_f1_old_uncleaned", "macro_f1_cleaned"]]) + "\n")
    w("* The Baseline numbers change: the reference is now SVM 0.8590 / LightGBM 0.6918 (tuned) and the augmented versions in section 1; the old 0.878/0.705/0.819/0.741 are superseded.")
    w("* Gate G1 must be rerun with sigma_robust (done in Part 2 of the overnight run).")

    w("\n## 7. Data cleaning rule\n")
    w((PP / "DATA_CLEANING_RULE.md").read_text())

    w("\n## 8. Reconstruction of a sensor block, both protocols\n")
    w("Mean over the 16 sensors; flagged evaluation records are excluded from these errors (`phase1/protocol_comparison_summary.csv`). "
      "Figure of the S01-S02 relation across batches: `phase1/figures/s01_s02_across_batches.png`.\n")
    s = read(PP / "phase1/protocol_comparison_summary.csv")
    if s is not None:
        keep = s[s["method"].isin(["ridge", "knn", "iterative", "median"])]
        cols = ["method", "space", "exclude_twin", "mae_temporal", "mae_iid", "drift_cost_mae", "medae_temporal", "medae_iid",
                "rmse_temporal", "rmse_iid", "r2_median_temporal", "r2_median_iid"]
        w(table(keep[cols], ".3f") + "\n")
    sens = read(PP / "phase1/sensitivity_line223.csv")
    w("Sensitivity to the borderline record (batch 2, line 223), rule unchanged (`phase1/sensitivity_line223.csv`):\n")
    w(table(sens) + "\n")

    # feature provenance of the final pipeline (gate P4)
    tr_df, _ = load_split(cfg)
    Xtr, ytr = xy(tr_df)
    pipe = fit_preprocessor(fin["spec"], Xtr, ytr, tr_df["batch"].to_numpy())
    Path(PP / "final").mkdir(parents=True, exist_ok=True)
    pipeline_provenance(pipe).to_csv(PP / "final/feature_provenance.csv", index=False)

    (PP / "REPORT.md").write_text("\n".join(out))
    print("report written:", PP / "REPORT.md")
    print({k: g["result"] for k, g in gates.items()})


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/preprocessing.yaml")
    main(ap.parse_args().config)
